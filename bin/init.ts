#!/usr/bin/env node
// ============================================================
// MeshWhisper CLI — `npx meshwhisper init`
// Interactive project setup: generates meshwhisper.config.ts
// and prints a quickstart guide tailored to the project.
// ============================================================

import * as rl from 'node:readline';
import * as fs from 'node:fs';
import * as path from 'node:path';

// ---- Formatting helpers ----

const reset  = '\x1b[0m';
const bold   = '\x1b[1m';
const dim    = '\x1b[2m';
const cyan   = '\x1b[36m';
const green  = '\x1b[32m';
const yellow = '\x1b[33m';
const red    = '\x1b[31m';

function b(s: string)  { return `${bold}${s}${reset}`; }
function c(s: string)  { return `${cyan}${s}${reset}`; }
function g(s: string)  { return `${green}${s}${reset}`; }
function y(s: string)  { return `${yellow}${s}${reset}`; }
function d(s: string)  { return `${dim}${s}${reset}`; }

function header() {
  console.log('');
  console.log(`  ${bold}${cyan}MeshWhisper${reset}  ${dim}Serverless P2P E2EE Messaging SDK${reset}`);
  console.log(`  ${dim}${'─'.repeat(42)}${reset}`);
  console.log('');
}

function step(n: number, label: string) {
  console.log(`  ${bold}${cyan}${n}.${reset} ${label}`);
}

function info(msg: string) {
  console.log(`     ${dim}${msg}${reset}`);
}

function success(msg: string) {
  console.log(`  ${green}✓${reset}  ${msg}`);
}

function warn(msg: string) {
  console.log(`  ${yellow}!${reset}  ${msg}`);
}

// ---- Prompt helpers ----

/**
 * Simple line-queue prompter that works in both interactive TTY and piped mode.
 *
 * In TTY mode:  prints the prompt and waits for the user to press Enter.
 * In pipe mode: reads lines collected from stdin before the first prompt fires,
 *               then dequeues answers one at a time (no blocking readline issue).
 */
class Prompter {
  private lineQueue: string[] = [];
  private lineResolvers: Array<(line: string) => void> = [];
  private iface: rl.Interface;
  private closed = false;

  constructor() {
    this.iface = rl.createInterface({
      input: process.stdin,
      output: process.stdout,
      terminal: process.stdin.isTTY ?? false,
    });

    this.iface.on('line', (line) => {
      if (this.lineResolvers.length > 0) {
        this.lineResolvers.shift()!(line);
      } else {
        this.lineQueue.push(line);
      }
    });

    this.iface.on('close', () => {
      this.closed = true;
      // Resolve any waiting promises with empty string (→ default will apply)
      for (const resolve of this.lineResolvers) {
        resolve('');
      }
      this.lineResolvers = [];
    });
  }

  private nextLine(): Promise<string> {
    if (this.lineQueue.length > 0) {
      return Promise.resolve(this.lineQueue.shift()!);
    }
    if (this.closed) {
      return Promise.resolve('');
    }
    return new Promise((resolve) => {
      this.lineResolvers.push(resolve);
    });
  }

  async ask(question: string, fallback: string): Promise<string> {
    process.stdout.write(`  ${b('?')} ${question} ${d(`(${fallback})`)} › `);
    const answer = (await this.nextLine()).trim();
    if (process.stdout.isTTY) process.stdout.write('\n');
    return answer === '' ? fallback : answer;
  }

  async confirm(question: string, defaultYes = true): Promise<boolean> {
    const hint = defaultYes ? 'Y/n' : 'y/N';
    process.stdout.write(`  ${b('?')} ${question} ${d(`[${hint}]`)} › `);
    const answer = (await this.nextLine()).trim().toLowerCase();
    if (process.stdout.isTTY) process.stdout.write('\n');
    if (answer === '') return defaultYes;
    return answer === 'y' || answer === 'yes';
  }

  close() {
    if (!this.closed) {
      this.iface.close();
    }
  }
}

// ---- Config file template ----

function generateConfig(opts: {
  namespace: string;
  peerName: string;
  relayUrl: string;
  storageDir: string;
}) {
  return `// meshwhisper.config.ts
// Generated by \`npx meshwhisper init\`
//
// Import this in your server-side entry point and pass to MeshWhisper.init().

import { NodeStorage } from '@meshwhisper/sdk/persistence/node';
import type { MeshWhisperConfig } from '@meshwhisper/sdk';

export const config: MeshWhisperConfig = {
  // Human-readable display name for this peer
  peerName: ${JSON.stringify(opts.peerName)},

  // Namespace isolates your mesh from other deployments on the same relay.
  // Use a unique string — e.g. your app name or a UUID.
  namespace: ${JSON.stringify(opts.namespace)},

  // Relay WebSocket URL.  Run \`npx @meshwhisper/relay\` to start a local relay.
  relayUrl: ${JSON.stringify(opts.relayUrl)},

  // Persistent identity + session storage (Node.js).
  // Switch to IdbStorage for browser environments.
  storage: new NodeStorage(${JSON.stringify(opts.storageDir)}),

  // Optional: tune transport behaviour
  // maxRelayLatency: 5000,
  // chaffIntervalMs: 30_000,
};
`;
}

// ---- Quickstart guide ----

function printQuickstart(opts: {
  namespace: string;
  relayUrl: string;
  configFile: string;
  hasRelay: boolean;
}) {
  console.log('');
  console.log(`  ${bold}${green}Setup complete!${reset}`);
  console.log('');
  console.log(`  ${bold}Next steps${reset}`);
  console.log('');

  let stepN = 1;

  if (!opts.hasRelay) {
    step(stepN++, 'Start a relay (needs to run once, can be shared):');
    info('npm install -g @meshwhisper/relay');
    info('meshwhisper-relay              # listens on ws://localhost:8080');
    console.log('');
  }

  step(stepN++, 'Use the config in your app:');
  info(`import { MeshWhisper } from '@meshwhisper/sdk/node';`);
  info(`import { config }     from './${path.basename(opts.configFile)}';`);
  console.log('');
  info(`const sdk = await MeshWhisper.init(config);`);
  console.log('');

  step(stepN++, 'Exchange contacts (one-time, out-of-band):');
  info(`const { qr } = sdk.generateContactQR();`);
  info(`// Share \`qr\` with the other peer over any channel`);
  info(`await sdk.acceptContact(qr);`);
  console.log('');

  step(stepN++, 'Send and receive messages:');
  info(`sdk.on('message', ({ from, payload }) => {`);
  info(`  console.log(from, new TextDecoder().decode(payload));`);
  info(`});`);
  console.log('');
  info(`await sdk.sendMessage(peerId, new TextEncoder().encode('Hello!'));`);
  console.log('');

  step(stepN++, 'Run the interactive demo (two terminals):');
  info('npm run demo:alice   # starts on :3001');
  info('npm run demo:bob     # starts on :3002');
  info('# Open http://localhost:3001 and http://localhost:3002');
  console.log('');

  console.log(`  ${dim}Docs & source → https://github.com/meshwhisper/meshwhisper${reset}`);
  console.log('');
}

// ---- Main ----

async function main() {
  header();

  console.log(`  Welcome to ${b('MeshWhisper')}. This wizard creates a ${c('meshwhisper.config.ts')}`);
  console.log(`  in your project and walks you through the first steps.\n`);

  const prompter = new Prompter();

  try {
    // 1. Peer / app name
    const peerName = await prompter.ask('What should this peer be called?', 'alice');

    // 2. Namespace
    const defaultNs = peerName.toLowerCase().replace(/[^a-z0-9-]/g, '-');
    const namespace = await prompter.ask(
      'Namespace for your mesh (isolates peers on shared relays)',
      `${defaultNs}-mesh`,
    );

    // 3. Relay URL
    const relayUrl = await prompter.ask('Relay WebSocket URL', 'ws://localhost:8080');

    // 4. Storage directory
    const storageDir = await prompter.ask(
      'Local storage directory (for identity + sessions)',
      `./.meshwhisper/${namespace}`,
    );

    // 5. Output file location
    const configFile = await prompter.ask('Save config to', 'meshwhisper.config.ts');

    // 6. Overwrite check
    const configPath = path.resolve(process.cwd(), configFile);
    const exists = fs.existsSync(configPath);
    let shouldWrite = true;

    if (exists) {
      const overwrite = await prompter.confirm(`${y(configFile)} already exists — overwrite?`, false);
      if (!overwrite) {
        prompter.close();
        console.log(`\n  ${dim}Aborted. No files changed.${reset}\n`);
        return;
      }
    }

    // 7. Gitignore check
    const gitignorePath = path.resolve(process.cwd(), '.gitignore');
    let addToGitignore = false;
    let dirToIgnore = '';
    if (fs.existsSync(gitignorePath)) {
      const gitignore = fs.readFileSync(gitignorePath, 'utf8');
      dirToIgnore = storageDir.startsWith('./') ? storageDir.slice(2) : storageDir;
      if (!gitignore.includes(dirToIgnore)) {
        addToGitignore = await prompter.confirm(
          `Add ${d(storageDir)} to .gitignore? ${d('(contains private keys)')}`,
          true,
        );
      }
    }

    // All interactive input done — close before any async network/IO
    prompter.close();

    // 8. Check if relay is reachable
    let hasRelay = false;
    console.log('');
    console.log(`  ${dim}Checking relay at ${relayUrl}…${reset}`);
    try {
      const httpUrl = relayUrl.replace(/^ws/, 'http') + '/health';
      const resp = await fetch(httpUrl, { signal: AbortSignal.timeout(3000) });
      if (resp.ok) {
        success(`Relay is reachable ${d('(' + relayUrl + ')')}`);
        hasRelay = true;
      } else {
        warn(`Relay returned HTTP ${resp.status} — you may need to start it`);
      }
    } catch {
      warn(`Could not reach relay — remember to start it before running your app`);
    }

    // 9. Write config
    console.log('');
    if (shouldWrite) {
      fs.mkdirSync(path.dirname(configPath), { recursive: true });
      const configContent = generateConfig({ namespace, peerName, relayUrl, storageDir });
      fs.writeFileSync(configPath, configContent, 'utf8');
      success(`Config written to ${c(configFile)}`);
    }

    // 10. Update .gitignore
    if (addToGitignore && dirToIgnore) {
      fs.appendFileSync(gitignorePath, `\n# MeshWhisper local identity/session store\n${dirToIgnore}\n`);
      success(`.gitignore updated`);
    }

    printQuickstart({ namespace, relayUrl, configFile, hasRelay });
  } catch (err) {
    prompter.close();
    throw err;
  }
}

main().catch((err) => {
  console.error(`\n  ${red}Error:${reset} ${err.message ?? err}\n`);
  process.exit(1);
});
